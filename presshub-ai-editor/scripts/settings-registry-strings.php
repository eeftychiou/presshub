<?php
/**
 * Generates includes/settings-registry-strings.php from the settings registry (#309, E10).
 *
 * The registry (includes/settings-registry-data.php) is plain data, so its
 * labels, help texts and old names are not seen by the .pot generator. This
 * writes them as __() calls in a file that is never executed, so translators
 * get every string, and PressHub_Settings_Registry::search_index() translates
 * them at run time with translate().
 *
 * Usage:  php presshub-ai-editor/scripts/settings-registry-strings.php           (writes the file)
 *         php presshub-ai-editor/scripts/settings-registry-strings.php --check   (exit 1 if stale)
 */

if ( ! defined( 'ABSPATH' ) ) {
    define( 'ABSPATH', __DIR__ . '/' );
}

/**
 * A PHP string literal the .pot generator reads: single quotes, or double
 * quotes when the text has an apostrophe (make-pot does not read \' escapes).
 */
function presshub_settings_registry_strings_literal( string $text ): string {
    if ( false === strpos( $text, "'" ) ) {
        return "'" . str_replace( '\\', '\\\\', $text ) . "'";
    }
    return '"' . str_replace( [ '\\', '"', '$' ], [ '\\\\', '\\"', '\\$' ], $text ) . '"';
}

/** The PHP source of the strings file for the current registry. */
function presshub_settings_registry_strings_source(): string {
    $data    = include dirname( __DIR__ ) . '/includes/settings-registry-data.php';
    $strings = [];
    foreach ( (array) $data as $entry ) {
        foreach ( [ 'label', 'help' ] as $field ) {
            $text = trim( (string) ( $entry[ $field ] ?? '' ) );
            if ( '' !== $text ) {
                $strings[ $text ] = true;
            }
        }
        foreach ( (array) ( $entry['aliases'] ?? [] ) as $alias ) {
            $text = trim( (string) $alias );
            if ( '' !== $text ) {
                $strings[ $text ] = true;
            }
        }
    }
    $out  = "<?php\n";
    $out .= "/**\n * Settings registry strings, for translators (#309, E10).\n *\n";
    $out .= " * Generated by scripts/settings-registry-strings.php from\n * includes/settings-registry-data.php. Do not edit by hand: run the script.\n";
    $out .= " * Never loaded: it only lets the .pot generator see the registry's labels,\n * help texts and old names, which search_index() translates with translate().\n *\n";
    $out .= " * @package presshub-ai-editor\n */\n\n";
    $out .= "if ( ! defined( 'ABSPATH' ) ) {\n    exit;\n}\n\n";
    $out .= "// phpcs:disable\nreturn;\n\n";
    foreach ( array_keys( $strings ) as $text ) {
        $out .= '__( ' . presshub_settings_registry_strings_literal( $text ) . ", 'presshub-ai-editor' );\n";
    }
    return $out;
}

if ( PHP_SAPI === 'cli' && isset( $argv ) && realpath( $argv[0] ) === realpath( __FILE__ ) ) {
    $target = dirname( __DIR__ ) . '/includes/settings-registry-strings.php';
    $source = presshub_settings_registry_strings_source();
    if ( in_array( '--check', $argv, true ) ) {
        $current = is_readable( $target ) ? str_replace( "\r\n", "\n", (string) file_get_contents( $target ) ) : '';
        if ( $current !== $source ) {
            fwrite( STDERR, "includes/settings-registry-strings.php is stale. Run: php presshub-ai-editor/scripts/settings-registry-strings.php\n" );
            exit( 1 );
        }
        echo "settings-registry-strings.php is up to date.\n";
        exit( 0 );
    }
    file_put_contents( $target, $source );
    echo 'Wrote ' . substr_count( $source, "\n__( " ) . " strings to includes/settings-registry-strings.php\n";
}
